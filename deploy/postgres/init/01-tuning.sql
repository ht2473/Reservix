-- =============================================================================
-- Reservix — инициализация кластера PostgreSQL
--
-- Скрипт выполняется единожды, при первом создании тома с данными.
-- Расширения устанавливаются миграцией Django (core/0001_postgres_extensions),
-- здесь настраиваются только параметры уровня кластера.
-- =============================================================================

-- Часовой пояс кластера. Приложение хранит время в UTC и переводит его в
-- пояс пользователя при выводе, но значение по умолчанию влияет на ручные
-- запросы администратора и на содержимое резервных копий.
ALTER SYSTEM SET timezone = 'UTC';

-- Журналирование медленных запросов: всё, что выполняется дольше 500 мс,
-- попадает в лог и становится предметом разбора.
ALTER SYSTEM SET log_min_duration_statement = 500;

-- Фиксация блокировок, ожидание которых превысило секунду: типичный
-- источник «зависаний» интерфейса при массовом пересчёте показателей.
ALTER SYSTEM SET log_lock_waits = on;
ALTER SYSTEM SET deadlock_timeout = '1s';

-- Автоочистка настраивается агрессивнее значений по умолчанию: таблицы
-- снимков индекса готовности и журнала аудита растут постоянно.
ALTER SYSTEM SET autovacuum_vacuum_scale_factor = 0.05;
ALTER SYSTEM SET autovacuum_analyze_scale_factor = 0.02;

SELECT pg_reload_conf();
