class Command(BaseCommand):
    """Наполняет публичную часть содержимым."""

    help = "Создаёт материалы базы знаний, глоссарий, справку и статические страницы"

    def add_arguments(self, parser) -> None:
        parser.add_argument("--flush", action="store_true", help="удалить существующее содержимое")

    @transaction.atomic
    def handle(self, *args, **options) -> None:
        if options["flush"]:
            Article.objects.all().delete()
            ArticleCategory.objects.all().delete()
            GlossaryTerm.objects.all().delete()
            FaqItem.objects.all().delete()
            FaqCategory.objects.all().delete()
            Page.objects.all().delete()
            self.stdout.write(self.style.WARNING("Содержимое публичной части удалено"))

        categories = self._create_categories()
        articles = self._create_articles(categories)
        terms = self._create_glossary()
        questions = self._create_faq()
        pages = self._create_pages()

        self.stdout.write(
            self.style.SUCCESS(
                f"Публичная часть наполнена: разделов {len(categories)}, "
                f"материалов {articles}, терминов {terms}, вопросов {questions}, "
                f"страниц {pages}"
            )
        )

    def _create_categories(self) -> dict[str, ArticleCategory]:
        created: dict[str, ArticleCategory] = {}
        for order, (slug, name, icon, description) in enumerate(CATEGORIES, start=1):
            category, _is_new = ArticleCategory.objects.update_or_create(
                slug=slug,
                defaults={
                    "name": name,
                    "icon": icon,
                    "description": description,
                    "sort_order": order,
                },
            )
            created[slug] = category
        return created

    def _create_articles(self, categories: dict[str, ArticleCategory]) -> int:
        """Создаёт материалы базы знаний."""
        import datetime as dt

        moment = timezone.now()
        created = 0

        for offset, spec in enumerate(ARTICLES):
            Article.objects.update_or_create(
                title=spec["title"],
                defaults={
                    "category": categories[spec["category"]],
                    "summary": spec["summary"],
                    "body": spec["body"].strip(),
                    "tags": spec["tags"],
                    "is_published": True,
                    "published_at": moment - dt.timedelta(days=7 * offset),
                },
            )
            created += 1
        return created

    def _create_glossary(self) -> int:
        created = 0
        for term, english, definition in GLOSSARY:
            GlossaryTerm.objects.update_or_create(
                term=term,
                defaults={
                    "english": english,
                    "definition": definition,
                    "is_published": True,
                },
            )
            created += 1
        return created

    def _create_faq(self) -> int:
        created = 0
        for order, (slug, name, audience, items) in enumerate(FAQ, start=1):
            category, _is_new = FaqCategory.objects.update_or_create(
                slug=slug,
                defaults={"name": name, "audience": audience, "sort_order": order},
            )
            for position, (question, answer) in enumerate(items, start=1):
                FaqItem.objects.update_or_create(
                    category=category,
                    question=question,
                    defaults={
                        "answer": answer,
                        "sort_order": position,
                        "is_published": True,
                    },
                )
                created += 1
        return created

    def _create_pages(self) -> int:
        for spec in PAGES:
            Page.objects.update_or_create(
                slug=spec["slug"],
                defaults={
                    "title": spec["title"],
                    "subtitle": spec["subtitle"],
                    "body": str(spec["body"]).strip(),
                    "meta_description": spec["meta_description"],
                    "show_in_footer": spec["show_in_footer"],
                    "is_published": True,
                },
            )
        return len(PAGES)
