@dataclass(frozen=True, slots=True)
class CategorySpec:
    """Категория справочника компетенций."""

    code: str
    name: str
    kind: str
    color: str
    description: str


@dataclass(frozen=True, slots=True)
class CompetencySpec:
    """Компетенция корпоративной модели вместе со шкалой."""

    code: str
    name: str
    category: str
    definition: str
    development_hint: str
    indicators: tuple[str, str, str, str, str]
    kind: str = ""
    is_core: bool = False
    is_testable: bool = False

    def resolved_kind(self, category_kind: str) -> str:
        """Тип компетенции; по умолчанию наследуется от категории."""
        return self.kind or category_kind


@dataclass(frozen=True, slots=True)
class RequirementSpec:
    """Требование модели: компетенция, целевой уровень, вес, критичность."""

    competency: str
    target: int
    weight: float
    minimum: int | None = None
    is_critical: bool = False


@dataclass(frozen=True, slots=True)
class ModelSpec:
    """Модель компетенций: набор требований для группы должностей."""

    code: str
    name: str
    description: str
    requirements: tuple[RequirementSpec, ...]
    grade_code: str = ""
    grade_range: tuple[int, int] = (0, 0)
    departments: tuple[str, ...] = ()
    is_functional: bool = False
    positions: tuple[str, ...] = field(default_factory=tuple)


